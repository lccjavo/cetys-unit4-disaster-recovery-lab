-- 001_schema.sql
-- Hotel Management App schema (CETYS Unit 4).
-- Idempotent: can run multiple times without deleting data.

CREATE EXTENSION IF NOT EXISTS unaccent;

-- Lab metadata (for example, the marker that the seed already ran).
CREATE TABLE IF NOT EXISTS lab_metadata (
    key         text PRIMARY KEY,
    value       text NOT NULL,
    updated_at  timestamptz NOT NULL DEFAULT now()
);

-- Login accounts (administrators, hotel staff and customers).
CREATE TABLE IF NOT EXISTS users (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username       text NOT NULL UNIQUE,
    password_hash  text NOT NULL,                 -- Argon2id
    role           text NOT NULL CHECK (role IN ('admin', 'staff', 'customer')),
    display_name   text NOT NULL,
    is_active      boolean NOT NULL DEFAULT true,
    created_at     timestamptz NOT NULL DEFAULT now(),
    last_login_at  timestamptz
);

-- Customer profile: basic identity + the 20 OPERATIONAL fields (no application-level encryption).
CREATE TABLE IF NOT EXISTS customers (
    id                        bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id                   bigint NOT NULL UNIQUE REFERENCES users(id) ON DELETE CASCADE,
    customer_code             text NOT NULL UNIQUE,
    full_name                 text NOT NULL,
    status                    text NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'vip', 'inactive', 'suspended')),
    -- 20 operational / lower-sensitivity fields
    display_nickname          text NOT NULL,
    city                      text NOT NULL,
    country                   text NOT NULL,
    preferred_language        text NOT NULL,
    time_zone                 text NOT NULL,
    preferred_currency        text NOT NULL,
    preferred_room_category   text NOT NULL,
    preferred_bed_type        text NOT NULL,
    preferred_floor           text NOT NULL,
    preferred_room_view       text NOT NULL,
    preferred_pillow_type     text NOT NULL,
    preferred_checkin_time    text NOT NULL,
    preferred_checkout_time   text NOT NULL,
    breakfast_preference      text NOT NULL,
    parking_required          boolean NOT NULL DEFAULT false,
    wifi_usage_preference     text NOT NULL,
    newsletter_opt_in         boolean NOT NULL DEFAULT false,
    loyalty_tier              text NOT NULL,
    preferred_contact_channel text NOT NULL,
    favorite_amenity          text NOT NULL,
    -- bookkeeping
    is_seed                   boolean NOT NULL DEFAULT false,
    created_at                timestamptz NOT NULL DEFAULT now(),
    updated_at                timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS customers_country_city_idx ON customers (country, city);
CREATE INDEX IF NOT EXISTS customers_status_idx ON customers (status);

-- The 20 SENSITIVE fields, encrypted with AES-256-GCM BEFORE they reach PostgreSQL.
-- encrypted_fields = { "<field>": { "alg", "v", "nonce", "ciphertext", "tag" }, ... }
CREATE TABLE IF NOT EXISTS customer_sensitive_data (
    customer_id                bigint PRIMARY KEY REFERENCES customers(id) ON DELETE CASCADE,
    encrypted_fields           jsonb NOT NULL CHECK (jsonb_typeof(encrypted_fields) = 'object'),
    encryption_algorithm       text NOT NULL DEFAULT 'AES-256-GCM',
    encryption_schema_version  integer NOT NULL DEFAULT 1,
    encrypted_at               timestamptz NOT NULL DEFAULT now(),
    updated_at                 timestamptz NOT NULL DEFAULT now()
);

-- Each customer's DEK, WRAPPED by a Key Vault KEK. Plaintext DEKs or KEKs are never stored.
CREATE TABLE IF NOT EXISTS customer_keys (
    customer_id                bigint PRIMARY KEY REFERENCES customers(id) ON DELETE CASCADE,
    dek_ref                    uuid NOT NULL UNIQUE,
    wrapped_dek                text NOT NULL,      -- base64(AES-256-GCM(KEK, DEK))
    dek_wrap_nonce             text NOT NULL,      -- base64, 96 bits
    dek_wrap_tag               text NOT NULL,      -- base64, 128 bits
    kek_id                     text NOT NULL,      -- reference to the KEK (not the key)
    wrap_algorithm             text NOT NULL DEFAULT 'AES-256-GCM',
    encryption_schema_version  integer NOT NULL DEFAULT 1,
    created_at                 timestamptz NOT NULL DEFAULT now(),
    rewrapped_at               timestamptz
);
CREATE INDEX IF NOT EXISTS customer_keys_kek_idx ON customer_keys (kek_id);

-- Fictional hotel reservations.
CREATE TABLE IF NOT EXISTS reservations (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reservation_code    text NOT NULL UNIQUE,
    customer_id         bigint NOT NULL REFERENCES customers(id) ON DELETE CASCADE,
    room_type           text NOT NULL CHECK (room_type IN ('Single', 'Double', 'Junior Suite', 'Executive Suite', 'Family')),
    room_number         text,
    check_in            date NOT NULL,
    check_out           date NOT NULL,
    guests_count        integer NOT NULL DEFAULT 1 CHECK (guests_count BETWEEN 1 AND 8),
    status              text NOT NULL CHECK (status IN ('pending', 'confirmed', 'checked_in', 'checked_out', 'cancelled')),
    total_amount        numeric(12,2) NOT NULL DEFAULT 0,
    created_by_user_id  bigint REFERENCES users(id) ON DELETE SET NULL,
    created_at          timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT reservations_dates_chk CHECK (check_out > check_in)
);
CREATE INDEX IF NOT EXISTS reservations_customer_idx ON reservations (customer_id);
CREATE INDEX IF NOT EXISTS reservations_checkin_idx ON reservations (check_in);

-- Audit log. Never contains plaintext sensitive values.
CREATE TABLE IF NOT EXISTS audit_events (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    occurred_at    timestamptz NOT NULL DEFAULT now(),
    actor_user_id  bigint REFERENCES users(id) ON DELETE SET NULL,
    actor_username text,
    action         text NOT NULL,
    target_type    text,
    target_id      text,
    outcome        text NOT NULL CHECK (outcome IN ('success', 'denied', 'error')),
    details        jsonb NOT NULL DEFAULT '{}'::jsonb,
    source_ip      text
);
CREATE INDEX IF NOT EXISTS audit_events_time_idx ON audit_events (occurred_at DESC);

-- Recovery verifications run from the GUI or the scripts.
CREATE TABLE IF NOT EXISTS recovery_verifications (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    verified_at         timestamptz NOT NULL DEFAULT now(),
    db_server           text NOT NULL,
    customers_count     integer NOT NULL,
    reservations_count  integer NOT NULL,
    sampled_customers   integer NOT NULL,
    decrypted_ok        integer NOT NULL,
    outcome             text NOT NULL CHECK (outcome IN ('success', 'partial', 'failed')),
    details             jsonb NOT NULL DEFAULT '{}'::jsonb
);
